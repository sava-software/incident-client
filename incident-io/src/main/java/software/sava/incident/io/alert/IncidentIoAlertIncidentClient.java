package software.sava.incident.io.alert;

import software.sava.incident.core.api.IncidentAlert;
import software.sava.incident.core.api.IncidentClient;
import software.sava.incident.core.api.IncidentResponse;
import software.sava.incident.core.json.Rfc3339;

import java.net.URI;
import java.net.http.HttpClient;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Objects;
import java.util.concurrent.CompletableFuture;

import static java.util.Objects.requireNonNullElse;

/// Adapts an [IncidentIoAlertEventClient] to the provider-neutral [IncidentClient]: a report
/// sends a [AlertEvent.Status#firing] event to the HTTP alert source, and a resolve sends a
/// [AlertEvent.Status#resolved] event with the same deduplication key.
///
/// This provider's key and resolve address the *alert's* lifecycle. Whether an incident is
/// created from the alert, and what happens to that incident when the alert resolves, depends
/// on the workspace's alert routes, so [#supportsResolve()] being true does not promise that
/// an incident closes.
///
/// The report maps the alert's `summary` to the event `title`, its `details` to the
/// `description`, and its key to the `deduplication_key` (a blank key is generated by the
/// event builder and returned in the response). `metadata` carries, in this order, `severity`
/// (the [software.sava.incident.core.api.IncidentSeverity] name in lower case), `source` when
/// not blank, `timestamp` in RFC 3339 when set, and then every custom detail in iteration
/// order; a custom detail named `severity`, `source` or `timestamp` replaces that value in
/// place. A custom detail value the event would refuse (a `Map`, an array, a collection
/// holding a container, a nonfinite number) is sent as its `String.valueOf` text instead, so
/// an alert is never dropped for the shape of a detail, and one with a null key is skipped.
///
/// The schema requires a `title` on every event, and neither the schema nor the vendor's
/// documentation says whether a resolve event's title replaces the alert's. A resolve
/// therefore sends [Builder#resolveTitle(String)] when one is configured, and otherwise the
/// key itself. A resolve with a null or blank key throws at once and sends nothing.
public final class IncidentIoAlertIncidentClient implements IncidentClient {

  public static Builder build(final IncidentIoAlertEventClient client) {
    return new Builder(client);
  }

  private final IncidentIoAlertEventClient client;
  private final String resolveTitle;

  private IncidentIoAlertIncidentClient(final IncidentIoAlertEventClient client, final String resolveTitle) {
    this.client = client;
    this.resolveTitle = resolveTitle;
  }

  static AlertEvent toEvent(final IncidentAlert alert) {
    final var metadata = new LinkedHashMap<String, Object>();
    metadata.put("severity", alert.severity().name().toLowerCase(Locale.ROOT));
    final var source = alert.source();
    if (source != null && !source.isBlank()) {
      metadata.put("source", source);
    }
    final var timestamp = alert.timestamp();
    if (timestamp != null) {
      // a region zone would render an invalid [Area/City] suffix; RFC 3339 needs the offset
      metadata.put("timestamp", Rfc3339.format(timestamp));
    }
    alert.customDetails().forEach((key, value) -> {
      if (key != null) {
        metadata.put(key, AlertEventRecord.refusesMetadataValue(value) ? String.valueOf(value) : value);
      }
    });
    return AlertEvent.build()
        .status(AlertEvent.Status.firing)
        .title(alert.summary())
        .description(alert.details())
        .deduplicationKey(alert.key())
        .metadata(metadata)
        .create();
  }

  @Override
  public CompletableFuture<IncidentResponse> reportIncident(final IncidentAlert alert) {
    return send(toEvent(alert));
  }

  @Override
  public boolean supportsResolve() {
    return true;
  }

  /// Sends a resolved event for `key`.
  ///
  /// A null or blank key is a caller error, not a failed delivery: it is thrown before
  /// anything is sent rather than failing the returned future, so a retrying caller such as
  /// [software.sava.incident.core.api.IncidentService] does not retry it as a transport
  /// failure.
  ///
  /// @throws NullPointerException     if `key` is null
  /// @throws IllegalArgumentException if `key` is blank
  @Override
  public CompletableFuture<IncidentResponse> resolveIncident(final String key) {
    if (key == null) {
      throw new NullPointerException("A resolve requires the alert's key.");
    }
    if (key.isBlank()) {
      throw new IllegalArgumentException("A resolve requires the alert's key.");
    }
    return send(AlertEvent.build()
        .status(AlertEvent.Status.resolved)
        .title(resolveTitle == null ? key : resolveTitle)
        .deduplicationKey(key)
        .create());
  }

  private CompletableFuture<IncidentResponse> send(final AlertEvent event) {
    final var sentKey = event.deduplicationKey();
    return client.sendAlertEvent(event).thenApply(response -> IncidentResponse.of(
        requireNonNullElse(response.deduplicationKey(), sentKey),
        response.status(),
        null
    ));
  }

  @Override
  public URI endpoint() {
    return client.endpoint();
  }

  @Override
  public HttpClient httpClient() {
    return client.httpClient();
  }

  @Override
  public String toString() {
    return "IncidentIoAlertIncidentClient{client=" + client + '}';
  }

  public static final class Builder {

    private final IncidentIoAlertEventClient client;
    private String resolveTitle;

    private Builder(final IncidentIoAlertEventClient client) {
      this.client = Objects.requireNonNull(client, "'client' is required.");
    }

    public IncidentClient createClient() {
      return new IncidentIoAlertIncidentClient(client, resolveTitle);
    }

    /// The `title` sent with a resolve event; null or blank, the default, sends the key.
    public Builder resolveTitle(final String resolveTitle) {
      this.resolveTitle = resolveTitle == null || resolveTitle.isBlank() ? null : resolveTitle;
      return this;
    }

    public String resolveTitle() {
      return resolveTitle;
    }
  }
}
